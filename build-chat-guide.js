const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "skills/md2gost-report");
const read = file => fs.readFileSync(path.join(root, file), "utf8").replace(/\r\n/g, "\n");
const skill = read("SKILL.md");
const frontmatter = /^---\n[\s\S]*?\n---\n/.exec(skill)?.[0];
if (!frontmatter) throw new Error("Skill frontmatter was not found");
const referenceUrl = "https://github.com/MixelTe/md2gost/blob/master/skills/md2gost-report/references/";
const instructions = skill.slice(frontmatter.length)
	.replaceAll("(references/syntax.md)", "(#разметка-отчёта)")
	.replaceAll("(references/styles.md)", `(${referenceUrl}styles.md)`)
	.replaceAll("(references/rendering.md)", `(${referenceUrl}rendering.md)`);
const content = [
	frontmatter.trimEnd(),
	"<!-- Generated by build-chat-guide.js from SKILL.md and references/syntax.md. -->",
	"# Подготовка отчёта с md2gost в чате",
	"Следуй этим инструкциям при подготовке отчёта по заданию и приложенным материалам. Правила написания и необходимый синтаксис находятся в этом файле. Справочник стилей потребуется только при особых требованиях к оформлению; его можно открыть по ссылке ниже или получить отдельным вложением. Если нужные материалы недоступны, сообщи об этом и продолжай доступную часть работы.",
	nestHeadings(instructions),
	nestHeadings(read("references/syntax.md")),
].map(part => part.trim()).join("\n\n") + "\n";
const output = path.join(__dirname, "md2gost-report-chat.md");
if (process.argv.includes("--check"))
{
	const current = fs.existsSync(output) ? fs.readFileSync(output, "utf8").replace(/\r\n/g, "\n") : "";
	if (current != content)
	{
		console.error("Chat guide is outdated. Run npm run build:chat-guide.");
		process.exitCode = 1;
	}
	else console.log("Chat guide is up to date.");
}
else
{
	fs.writeFileSync(output, content, "utf8");
	console.log(`Generated ${output}`);
}

function nestHeadings(markdown)
{
	let fence;
	return markdown.split("\n").map(line =>
	{
		const marker = /^(`{3,}|~{3,})(.*)$/.exec(line);
		if (marker)
		{
			if (!fence) fence = marker[1];
			else if (marker[1][0] == fence[0] && marker[1].length >= fence.length && !marker[2].trim()) fence = undefined;
			return line;
		}
		return fence ? line : line.replace(/^(#{1,5}) /, "#$1 ");
	}).join("\n");
}
